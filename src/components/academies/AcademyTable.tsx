import type { Academy, Payment } from "../../types/finance";
import { AcademyStatusBadge } from "./AcademyStatusBadge";

interface AcademyTableProps {
  academies: Academy[];
  payments: Payment[];
  onView: (academy: Academy) => void;
  onEdit: (academy: Academy) => void;
  onDelete: (academy: Academy) => void;
}

const planLabels = {
  one_time: "One Time",
  monthly: "Monthly",
  quarterly: "Quarterly",
  yearly: "Yearly",
  custom: "Custom",
};

function formatCurrency(amount: number) {
  return `\u20B9${amount.toLocaleString("en-IN")}`;
}

function getCollectedAmount(academyId: number | undefined, payments: Payment[]) {
  if (!academyId) return 0;

  return payments
    .filter((payment) => payment.academyId === academyId)
    .reduce((total, payment) => total + payment.amount, 0);
}

